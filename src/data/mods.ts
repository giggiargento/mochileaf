export function getModsByGame(gameSlug: string): Mod[] {
  return mods.filter((m) => m.gameSlug === gameSlug);
}

export function getVisualModsByGame(gameSlug: string): Mod[] {
  return getModsByGame(gameSlug).filter((m) => m.category === 'visual');
}

export function getEssentialModsByGame(gameSlug: string): Mod[] {
  return getModsByGame(gameSlug).filter((m) => m.category !== 'visual');
}
